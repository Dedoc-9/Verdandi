(* The P32 statements, frozen before their proofs (2026-11-14). Graphs.v is generated by orl/emit.py from the same
   definitions it renders as Orlog laws and as the native sweep program. Model: Flocq's FLT formats, binary64 as
   FLT(-1074, 53) and binary32 as FLT(-149, 24), both without an upper exponent bound, so no overflow, and the sign of
   a zero is not seen. Author: the assistant.

   T32: narrow, built from binary64 operations only, is the binary32 round-to-nearest-even of any binary64 value.
   SQRT32, RSQRT32, HYPOT32: each graph returns a faithful binary32 rounding of the exact real result (one of the two
   binary32 values that bracket it). The range premises are binary32's own: inputs are binary32 values below 2^128. *)
From Coq Require Import Reals.
From Flocq Require Import Core.
From MKF.f32 Require Import F32_Statement.
From MKF.p32 Require Import Graphs.
Open Scope R_scope.

Definition T32 : Prop := forall v : R, format64 v -> narrow v = RN32 v.

Definition SQRT32 : Prop :=
  forall x : R, format32 x -> 0 <= x -> faithful32 (sqrt x) (g_sqrt32 x).

Definition RSQRT32 : Prop :=
  forall x : R, format32 x -> 0 < x -> x < bpow radix2 128 -> faithful32 (/ sqrt x) (g_rsqrt32 x).

Definition HYPOT32 : Prop :=
  forall x y : R, format32 x -> format32 y -> Rabs x < bpow radix2 128 -> Rabs y < bpow radix2 128 ->
  faithful32 (sqrt (x * x + y * y)) (g_hypot32 x y).
