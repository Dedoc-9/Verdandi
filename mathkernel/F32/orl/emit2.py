# exp32, a staged function (2026-11-14). One definition, three renderings, as emit.py does for the first functions; kept
# in a file of its own so that emit.py, frozen under the P32 gate, stays byte for byte.
#   exp32(x) = narrow(S^12(P(R(x)))):  R: clamp x below at -160, divide by 4096 (exact for a binary32 x);
#   P: the degree-7 Taylor polynomial with whole coefficients, N(r)/5040, N = 5040 + r(5040 + r(2520 + r(840 + r(210 +
#   r(42 + r(7 + r)))))); S: one squaring, twelve times (exp(x) = exp(x/4096)^4096). No ln 2, no table, no integer part.
#   python -B emit2.py emit      writes gen/sweep2.c, gen/corpus_exp32.orl and its inputs
#   python -B emit2.py corpus    Orlog's arbiter against the native program, the Python graph and the IEEE cast
#   python -B emit2.py sweep     the resumable exhaustive sweep (every finite binary32 x <= XMAX)
#   python -B emit2.py coq [-]   the Coq graph, exp32/Graph.v
import decimal, json, math, os, random, struct, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__)); GEN = os.path.join(HERE, 'gen')
PY = sys.executable
XMAX_U = 0x42B17217                      # the largest binary32 x with exp(x) below binary32's largest number
N_INPUTS = (XMAX_U + 1) + 0x7f800000     # finite binary32 values at most XMAX: 3258020376
def lvl(c): return ('n', ('add', ('const', c), ('mul', ('var', 'r'), ('var', 'n'))))
STAGES = [   # (name, input variable, steps [(target, tree)], output variable, how many times)
    ('red', 'x', [('x', ('clamplo', ('var', 'x'), '-160.0')), ('r', ('div', ('var', 'x'), ('const', '4096.0')))], 'r', 1),
    ('poly', 'r', [('n', ('add', ('const', '7.0'), ('var', 'r')))] + [lvl(c) for c in ('42.0', '210.0', '840.0', '2520.0', '5040.0', '5040.0')]
                  + [('v', ('div', ('var', 'n'), ('const', '5040.0')))], 'v', 1),
    ('sq', 'v', [('v', ('mul', ('var', 'v'), ('var', 'v')))], 'v', 12),
]
OPS = {'add': ('+', 'plus'), 'sub': ('-', 'minus'), 'mul': ('*', 'times'), 'div': ('/', 'divided by')}
def steps():
    for _, _, ss, _, rep in STAGES:
        for _ in range(rep):
            for s in ss: yield s
def c_expr(e):
    if e[0] in ('var', 'const'): return e[1]
    return '(%s %s %s)' % (c_expr(e[1]), OPS[e[0]][0], c_expr(e[2]))
def orl_expr(e):
    if e[0] == 'var': return e[1] * 2
    if e[0] == 'const': return e[1]
    return '(%s %s %s)' % (orl_expr(e[1]), OPS[e[0]][1], orl_expr(e[2]))
def py_tree(e, env):
    if e[0] == 'var': return env[e[1]]
    if e[0] == 'const': return float(e[1])
    a, b = py_tree(e[1], env), py_tree(e[2], env)
    return a + b if e[0] == 'add' else a - b if e[0] == 'sub' else a * b if e[0] == 'mul' else a / b
def py_g(x):
    env = {'x': x}
    for t, e in steps():
        if e[0] == 'clamplo': env[t] = float(e[2]) if env[e[1][1]] < float(e[2]) else env[e[1][1]]
        else: env[t] = py_tree(e, env)
    return env['v']
KK, MM, TT, HH = 536870913.0, 1.5 * 2.0 ** -97, 2.0 ** -126, 2.0 ** -150
def py_narrow(v):
    if abs(v) <= HH: return v * 0.0
    if abs(v) < TT: return (v + MM) - MM
    c = KK * v
    return c - (c - v)
def f32(u): return struct.unpack('<f', struct.pack('<I', u))[0]
def r32(x): return struct.unpack('<f', struct.pack('<f', x))[0]
def bits(d): return struct.unpack('<Q', struct.pack('<d', d))[0]
def dbl(b): return struct.unpack('<d', struct.pack('<Q', b))[0]
def dec(d):
    s = format(decimal.Decimal(d), 'f')
    return s if '.' in s else s + '.0'

C_HEAD = r'''// Generated by emit2.py (2026-11-14) from the staged definition of exp32. Binary64 operations only.
// Build: clang -O2 -ffp-contract=off -fno-math-errno sweep2.c -o sweep2.exe
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
static const double KK = 536870913.0, MM = 0x1.8p-97, TT = 0x1p-126, HH = 0x1p-150;
static double narrow(double v) { if (fabs(v) <= HH) return v * 0.0; if (fabs(v) < TT) return (v + MM) - MM; double c = KK * v; return c - (c - v); }
static double from32(uint32_t u) { float f; memcpy(&f, &u, 4); return (double)f; }
static uint64_t bits(double d) { uint64_t u; memcpy(&u, &d, 8); return u; }
static double frombits(uint64_t u) { double d; memcpy(&d, &u, 8); return d; }
static int is32(double r) { return (double)(float)r == r; }
static void nb(double r, double *lo, double *hi) { float rf = (float)r; *lo = (double)nextafterf(rf, -INFINITY); *hi = (double)nextafterf(rf, INFINITY); }
'''
C_SWEEP = r'''
// Faithful means lo < exp(x) < hi for the binary32 neighbours lo, hi of the result. The true exp(x) is taken to lie
// within 2^-40 (relative) of the C runtime's exp: a result is counted faithful only if the whole of that interval is
// inside (lo, hi), not faithful if all of it is outside, and otherwise printed as ambiguous for an exact check.
static int sweep(uint32_t lo_u, uint32_t hi_u) {
  uint64_t n = 0, bad_narrow = 0, unfaithful = 0, amb = 0, not_cr = 0; uint32_t first = 0; int have = 0; const double T = 0x1p-40;
  for (uint64_t uu = lo_u; uu <= hi_u; uu++) { uint32_t u = (uint32_t)uu;
    if ((u & 0x7f800000u) == 0x7f800000u) continue;                 // infinities and NaNs
    if (!(u & 0x80000000u) && u > XMAX_U) continue;                 // above XMAX the binary32 result overflows
    double x = from32(u), y = g_exp32(x);
#ifdef PLANT_UNFAITHFUL
    y = y * (1.0 + 0x1p-22);
#endif
    double r = narrow(y); n++;
    if (bits(r) != bits((double)(float)y)) bad_narrow++;
    double e = exp(x), el = e * (1.0 - T), eh = e * (1.0 + T), lo, hi; int ok = 0, sure = 1;
    if (is32(r) && r >= 0) { nb(r, &lo, &hi); ok = lo < el && eh < hi; if (!ok && !(eh <= lo || el >= hi)) sure = 0; }
    if (!sure) { amb++; printf("AMB %08x\n", u); }
    else if (!ok) { unfaithful++; if (!have) { first = u; have = 1; } }
    if (r != (double)(float)e) not_cr++;
  }
  printf("exp32 %08x %08x n=%llu bad_narrow=%llu unfaithful=%llu amb=%llu not_cr=%llu first=%08x\n", lo_u, hi_u, (unsigned long long)n,
         (unsigned long long)bad_narrow, (unsigned long long)unfaithful, (unsigned long long)amb, (unsigned long long)not_cr, first);
  return 0; }
int main(int argc, char **argv) {
  if (argc == 4 && !strcmp(argv[1], "sweep")) return sweep((uint32_t)strtoul(argv[2], 0, 16), (uint32_t)strtoul(argv[3], 0, 16));
  if (argc == 3 && !strcmp(argv[1], "corpus") && !strcmp(argv[2], "exp32")) { unsigned long long a; char line[128];
    while (fgets(line, sizeof line, stdin)) { if (sscanf(line, "%llx", &a) == 1) printf("%016llx\n", (unsigned long long)bits(narrow(g_exp32(frombits(a))))); }
    return 0; }
  return 2; }
'''
