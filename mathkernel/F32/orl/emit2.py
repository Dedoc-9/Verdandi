         '§5 For each ii from 1 to 97, do the following.', '§5.1 Set mm to mm times 0.5.', '§6 Let tt be 1.0.',
         '§7 For each ii from 1 to 126, do the following.', '§7.1 Set tt to tt times 0.5.',
         '§8 Let hh be 1.0.', '§9 For each ii from 1 to 150, do the following.', '§9.1 Set hh to hh times 0.5.',
         '§10 To narrow the value, do the following.',
         '§10.1 If the absolute value of vv is at most hh, set vv to vv times 0.0.',
         '§10.2 Otherwise, if the absolute value of vv is less than tt, set vv to (vv plus mm) minus mm.',
         '§10.3 Otherwise, set vv to (kk times vv) minus ((kk times vv) minus vv).',
