# One definition per function, three renderings (2026-11-14): an Orlog corpus law, a native C sweep program, and
# (later) the Coq graph. Contract P32: result = narrow(E), E an expression in binary64 +, -, *, /, sqrt; narrow rounds a
# binary64 value to binary32 with Orlog's own operations (Veltkamp split by 2^29+1; below 2^-126 the add-and-subtract of
# 1.5*2^-97). Every backend runs this same operation sequence.
#   python -B emit.py emit            writes gen/sweep.c and gen/corpus_<fn>.orl (+ .json inputs)
#   python -B emit.py corpus          runs each corpus law through Orlog's arbiter and the native program; compares bits
import decimal, json, os, random, struct, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__)); GEN = os.path.join(HERE, 'gen')
PY = sys.executable
FUNCS = {   # name: (inputs, expression before narrow)
    'narrow':  (['x'], ('var', 'x')),
    'sqrt32':  (['x'], ('sqrt', ('var', 'x'))),
    'rsqrt32': (['x'], ('div', ('const', '1.0'), ('sqrt', ('var', 'x')))),
    'hypot32': (['x', 'y'], ('sqrt', ('add', ('mul', ('var', 'x'), ('var', 'x')), ('mul', ('var', 'y'), ('var', 'y'))))),
}
def c_expr(e):
    k = e[0]
    if k == 'var': return e[1]
    if k == 'const': return e[1]
    if k == 'sqrt': return 'sqrt(%s)' % c_expr(e[1])
    return '(%s %s %s)' % (c_expr(e[1]), {'add': '+', 'sub': '-', 'mul': '*', 'div': '/'}[k], c_expr(e[2]))
def orl_expr(e):
    k = e[0]
    if k == 'var': return e[1] * 2            # Orlog variables are xx, yy (one-letter names are avoided)
    if k == 'const': return e[1]
    if k == 'sqrt': return 'the square root of (%s)' % orl_expr(e[1])
    return '(%s %s %s)' % (orl_expr(e[1]), {'add': 'plus', 'sub': 'minus', 'mul': 'times', 'div': 'divided by'}[k], orl_expr(e[2]))
def py_eval(e, env):
    k = e[0]
    if k == 'var': return env[e[1]]
    if k == 'const': return float(e[1])
    if k == 'sqrt': return py_eval(e[1], env) ** 0.5 if False else __import__('math').sqrt(py_eval(e[1], env))
    a, b = py_eval(e[1], env), py_eval(e[2], env)
    return a + b if k == 'add' else a - b if k == 'sub' else a * b if k == 'mul' else a / b
KK, MM, TT, HH = 536870913.0, 1.5 * 2.0 ** -97, 2.0 ** -126, 2.0 ** -150
def py_narrow(v):
    if abs(v) <= HH: return v * 0.0
    if abs(v) < TT: return (v + MM) - MM
    c = KK * v
    return c - (c - v)
def f32(u): return struct.unpack('<f', struct.pack('<I', u))[0]
def bits(d): return struct.unpack('<Q', struct.pack('<d', d))[0]
def dec(d):
    s = format(decimal.Decimal(d), 'f')
    return s if '.' in s else s + '.0'

C_HEAD = r'''// Generated by emit.py (2026-11-14) from the function definitions. Binary64 operations only.
// Build: clang -O2 -ffp-contract=off -fno-math-errno sweep.c -o sweep.exe
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
typedef unsigned __int128 u128;
static const double KK = 536870913.0, MM = 0x1.8p-97, TT = 0x1p-126, HH = 0x1p-150;
static double narrow(double v) { if (fabs(v) <= HH) return v * 0.0; if (fabs(v) < TT) return (v + MM) - MM; double c = KK * v; return c - (c - v); }
static double from32(uint32_t u) { float f; memcpy(&f, &u, 4); return (double)f; }
static uint64_t bits(double d) { uint64_t u; memcpy(&u, &d, 8); return u; }
static double frombits(uint64_t u) { double d; memcpy(&d, &u, 8); return d; }
// v = m * 2^e with m odd (or 0), exactly
static void odd(double v, uint64_t *m, int *e) { int ex; double fr = frexp(v, &ex); *m = (uint64_t)ldexp(fr, 53); *e = ex - 53;
  while (*m && !(*m & 1)) { *m >>= 1; (*e)++; } }
// sign of (P * 2^E - 1), P < 2^120, exactly
static int cmp1(u128 P, int E) { if (E >= 0) return (P == 1 && E == 0) ? 0 : 1; int s = -E; if (s >= 127) return -1;
  u128 t = (u128)1 << s; return P < t ? -1 : P > t ? 1 : 0; }
static int is32(double r) { return (double)(float)r == r; }
static void nb(double r, double *lo, double *hi) { float rf = (float)r; *lo = (double)nextafterf(rf, -INFINITY); *hi = (double)nextafterf(rf, INFINITY); }
'''
C_SWEEPS = r'''
// faithful: lo < sqrt(x) < hi, i.e. lo^2 < x < hi^2 (squares of 24-bit numbers are exact in binary64)
static int faithful_sqrt(double x, double r) { double lo, hi; if (!is32(r)) return 0; nb(r, &lo, &hi); return (lo < 0 || lo * lo < x) && x < hi * hi; }
// faithful: lo < 1/sqrt(x) < hi, i.e. x*lo^2 < 1 < x*hi^2, in exact integers
static int faithful_rsqrt(double x, double r) { double lo, hi; if (!is32(r)) return 0; nb(r, &lo, &hi);
  uint64_t mx, ml, mh; int ex, el, eh; odd(x, &mx, &ex); odd(lo, &ml, &el); odd(hi, &mh, &eh);
  return cmp1((u128)mx * ml * ml, ex + 2 * el) < 0 && cmp1((u128)mx * mh * mh, ex + 2 * eh) > 0; }
static int sweep(const char *fn, uint32_t lo_u, uint32_t hi_u) {
  int is_sqrt = !strcmp(fn, "sqrt32"), is_nar = !strcmp(fn, "narrow");
  uint64_t n = 0, bad_narrow = 0, unfaithful = 0, not_cr = 0; uint32_t first = 0; int have = 0;
  for (uint64_t uu = lo_u; uu <= hi_u; uu++) { uint32_t u = (uint32_t)uu;
    if ((u & 0x7f800000u) == 0x7f800000u) continue;                 // infinities and NaNs
    double x = from32(u);
    if (is_nar) {                                                  // x, its upper tie point, and both binary64 neighbours of the tie
      double up = (double)nextafterf((float)x, INFINITY), m = 0.5 * (x + up);
      double ys[5] = { x, m, nextafter(m, -INFINITY), nextafter(m, INFINITY), x * (1.0 + 0x1p-40) };
      for (int i = 0; i < 5; i++) { double y = ys[i]; if (!(fabs(y) < 0x1.fffffep127)) continue; n++;
#ifdef PLANT_NARROW
        double c = 268435457.0 * y, r = c - (c - y);
#else
        double r = narrow(y);
#endif
        if (bits(r) != bits((double)(float)y)) { bad_narrow++; if (!have) { first = u; have = 1; } } }
      continue; }
    if (u & 0x80000000u) continue; if (!is_sqrt && u == 0) continue;  // domain: x >= 0 (sqrt), x > 0 (rsqrt)
    double y = is_sqrt ? sqrt(x) : 1.0 / sqrt(x);
#ifdef PLANT_UNFAITHFUL
    y = y * (1.0 + 0x1p-22);
#endif
    double r = narrow(y); n++;
    if (bits(r) != bits((double)(float)y)) bad_narrow++;
    int ok = is_sqrt ? faithful_sqrt(x, r) : faithful_rsqrt(x, r);
    if (!ok) { unfaithful++; if (!have) { first = u; have = 1; } }
    if (is_sqrt && r != (double)sqrtf((float)x)) not_cr++;
  }
  printf("%s %08x %08x n=%llu bad_narrow=%llu unfaithful=%llu not_cr=%llu first=%08x\n", fn, lo_u, hi_u, (unsigned long long)n,
         (unsigned long long)bad_narrow, (unsigned long long)unfaithful, (unsigned long long)not_cr, first);
  return 0; }
'''
def emit():
    os.makedirs(GEN, exist_ok=True)
    c = [C_HEAD]
    for name, (ins, e) in FUNCS.items():
        c.append('static double f_%s(%s) { return narrow(%s); }' % (name, ', '.join('double ' + i for i in ins), c_expr(e)))
    c.append(C_SWEEPS)
    c.append('int main(int argc, char **argv) {\n  if (argc == 5 && !strcmp(argv[1], "sweep")) return sweep(argv[2], (uint32_t)strtoul(argv[3], 0, 16), (uint32_t)strtoul(argv[4], 0, 16));\n'
             '  if (argc == 3 && !strcmp(argv[1], "corpus")) { unsigned long long a, b; char line[128];\n'
             '    while (fgets(line, sizeof line, stdin)) { int k = sscanf(line, "%llx %llx", &a, &b); double r = 0;')
    for name, (ins, e) in FUNCS.items():
        args = 'frombits(a)' if len(ins) == 1 else 'frombits(a), frombits(b)'
        c.append('      if (!strcmp(argv[2], "%s") && k >= %d) r = f_%s(%s);' % (name, len(ins), name, args))
    c.append('      printf("%016llx\\n", (unsigned long long)bits(r)); }\n    return 0; }\n  return 2; }')
    open(os.path.join(GEN, 'sweep.c'), 'w', encoding='utf-8', newline='\n').write('\n'.join(c) + '\n')
    rnd = random.Random(20261114)
    edge = [1, 2, 0x007fffff, 0x00800000, 0x00800001, 0x3f800000, 0x3f7fffff, 0x3f800001, 0x40000000, 0x40400000,
            0x7f7fffff, 0x7f000000, 0x00000100, 0x3effffff, 0x3f000000, 0x4b800000, 0x4b800001, 0x1e3ce508, 0x5f000000, 0x20000000]
    for name, (ins, e) in FUNCS.items():
        us = edge + [rnd.randrange(1, 0x7f800000) for _ in range(180)]
        special = None
        if name == 'narrow':
            import math
            base = [0.0, 2.0 ** -150, math.nextafter(2.0 ** -150, 0), math.nextafter(2.0 ** -150, 1), 2.0 ** -149, 1.5 * 2.0 ** -149, 2.5 * 2.0 ** -149,
                    2.0 ** -126, 2.0 ** -126 - 2.0 ** -150, 1.0 + 2.0 ** -24, 1.0 + 3 * 2.0 ** -24, 1.0 - 2.0 ** -25, 3.0000001, 2.0 ** 127 * 1.9999999]
            base += [f32(u) * (1 + rnd.random() * 2.0 ** -20) for u in us[:90]] + [0.5 * (f32(u) + f32(u + 1)) for u in us[90:150]]
            special = [[v] for b in base if abs(b) < 2.0 ** 127 for v in (b, -b)]
        if name == 'hypot32':   # keep the result below 2^128 and x*x, y*y above the binary64 subnormals: no extra limit needed in binary32
            us = [u for u in us if f32(u) < 2.0 ** 126]
        rows = special or [[f32(u)] + ([f32(rnd.choice(us))] if len(ins) == 2 else []) for u in us]
        if name == 'hypot32': rows = [r for r in rows if r[1] < 2.0 ** 126]
        json.dump([[bits(v) for v in r] for r in rows], open(os.path.join(GEN, 'corpus_%s.json' % name), 'w'))
        L = ['Title: Corpus of %s, a binary32 result carried in binary64.' % name,
             'Note: Generated by emit.py on 2026-11-14 for a backend agreement check. A scratch law, not ratified.',
             '§1 Decimals are floats.', '§2 Let vv be 0.0.', '§3 Let kk be 536870913.0.', '§4 Let mm be 1.5.',
             '§5 For each ii from 1 to 97, do the following.', '§5.1 Set mm to mm times 0.5.', '§6 Let tt be 1.0.',
             '§7 For each ii from 1 to 126, do the following.', '§7.1 Set tt to tt times 0.5.',
             '§8 Let hh be 1.0.', '§9 For each ii from 1 to 150, do the following.', '§9.1 Set hh to hh times 0.5.',
             '§10 To narrow the value, do the following.',
             '§10.1 If the absolute value of vv is at most hh, set vv to vv times 0.0.',
             '§10.2 Otherwise, if the absolute value of vv is less than tt, set vv to (vv plus mm) minus mm.',
             '§10.3 Otherwise, set vv to (kk times vv) minus ((kk times vv) minus vv).']
        k = 11
        for j, i in enumerate(ins):
            L.append('§%d Let %ss be the list %s.' % (k, i * 2, ', '.join(dec(r[j]) for r in rows[:-1]) + ' and ' + dec(rows[-1][j]))); k += 1
            L.append('§%d Let %s be 0.0.' % (k, i * 2)); k += 1
        L.append('§%d For each ii from 1 to %d, do the following.' % (k, len(rows)))
        for j, i in enumerate(ins): L.append('§%d.%d Set %s to item ii of %ss.' % (k, j + 1, i * 2, i * 2))
        n = len(ins)
        L += ['§%d.%d Set vv to %s.' % (k, n + 1, orl_expr(e)), '§%d.%d Narrow the value.' % (k, n + 2), '§%d.%d Say vv.' % (k, n + 3)]
        open(os.path.join(GEN, 'corpus_%s.orl' % name), 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
    print('emitted gen/sweep.c and %d corpus laws' % len(FUNCS))
def corpus():
    allok = True
    for name, (ins, e) in FUNCS.items():
        rows = json.load(open(os.path.join(GEN, 'corpus_%s.json' % name)))
        p = subprocess.run([PY, '-B', 'orl.py', 'run', os.path.join('..', 'gen', 'corpus_%s.orl' % name), '--workdir', os.path.join('..', 'wd'), '--show'],
                           cwd=os.path.join(HERE, 'O'), capture_output=True, text=True, encoding='utf-8')
        out = p.stdout.splitlines(); head = out[0] if out else p.stderr[:200]
        orl = [bits(float(decimal.Decimal(l))) for l in out[1:] if l.strip()]
        q = subprocess.run([os.path.join(GEN, 'sweep.exe'), 'corpus', name], input='\n'.join(' '.join('%x' % b for b in r) for r in rows) + '\n',
                           capture_output=True, text=True)
        nat = [int(l, 16) for l in q.stdout.split()]
        ref = [bits(py_narrow(py_eval(e, dict(zip(ins, [struct.unpack('<d', struct.pack('<Q', b))[0] for b in r]))))) for r in rows]
        cast = [bits(struct.unpack('<f', struct.pack('<f', py_eval(e, dict(zip(ins, [struct.unpack('<d', struct.pack('<Q', b))[0] for b in r])))))[0]) for r in rows]
        agree = 'agree [c99,python,rust]' in head and 'dissent []' in head and 'COMPLETED' in head
        ok = agree and orl == nat == ref == cast and len(orl) == len(rows)
        allok &= ok
        print('%-8s %3d inputs | arbiter: %s | orlog = native C = python graph = IEEE cast: %s' % (
            name, len(rows), 'reference COMPLETED, c99/python/rust agree' if agree else head[:90],
            'yes' if ok else 'NO (%d/%d/%d/%d lines; first diff %s)' % (len(orl), len(nat), len(ref), len(cast),
                next((i for i in range(min(len(orl), len(nat), len(ref))) if not (orl[i] == nat[i] == ref[i] == cast[i])), None))))
    print('CORPUS AGREEMENT %s' % ('HELD' if allok else 'FAILED')); sys.exit(0 if allok else 1)

def sweeps():
    """Resumable exhaustive sweeps: 64 chunks per sweep, one log line per chunk, keyed to sweep.c's hash."""
    import concurrent.futures, hashlib
    key = hashlib.sha256(open(os.path.join(GEN, 'sweep.c'), 'rb').read()).hexdigest()[:16]
    log = os.path.join(GEN, 'sweeps-%s.log' % key); done = set()
    if os.path.exists(log): done = set(tuple(l.split()[:3]) for l in open(log) if l.strip())
    jobs = []
    for fn, top in (('sqrt32', 0x80000000), ('rsqrt32', 0x80000000), ('narrow', 0x100000000)):
        step = top // 64
        for i in range(64):
            lo, hi = i * step, (i + 1) * step - 1
            if (fn, '%08x' % lo, '%08x' % hi) not in done: jobs.append((fn, lo, hi))
    def one(j):
        q = subprocess.run([os.path.join(GEN, 'sweep.exe'), 'sweep', j[0], '%x' % j[1], '%x' % j[2]], capture_output=True, text=True)
        return q.stdout.strip()
    with concurrent.futures.ThreadPoolExecutor(12) as ex:
        for line in ex.map(one, jobs):
            open(log, 'a').write(line + '\n')
    tot = {}
    for l in open(log):
        f = l.split(); d = tot.setdefault(f[0], {'chunks': 0, 'n': 0, 'bad_narrow': 0, 'unfaithful': 0, 'not_cr': 0})
        d['chunks'] += 1
        for kv in f[3:7]:
            k, v = kv.split('='); d[k] += int(v)
    ok = True
    for fn, d in sorted(tot.items()):
        good = d['chunks'] == 64 and d['bad_narrow'] == 0 and d['unfaithful'] == 0; ok &= good
        print('%-8s chunks %d/64 inputs %d | narrow differs from IEEE cast: %d | not faithful: %d | differs from correctly rounded: %s | %s' % (
            fn, d['chunks'], d['n'], d['bad_narrow'], d['unfaithful'], d['not_cr'] if fn == 'sqrt32' else 'n/a', 'ok' if good else 'FAIL'))
    print('SWEEPS %s (program %s)' % ('HELD' if ok and len(tot) == 3 else 'FAILED', key)); sys.exit(0 if ok and len(tot) == 3 else 1)

def coq_expr(e):
    k = e[0]
    if k == 'var': return e[1]
    if k == 'const': return {'1.0': '1'}[e[1]]
    if k == 'sqrt': return 'RN64 (sqrt %s)' % coq_atom(e[1])
    return 'RN64 (%s %s %s)' % (coq_atom(e[1]), {'add': '+', 'sub': '-', 'mul': '*', 'div': '/'}[k], coq_atom(e[2]))
def coq_atom(e): return coq_expr(e) if e[0] in ('var', 'const') else '(%s)' % coq_expr(e)
def coq():
    """The Coq graphs, from the same definitions: every binary64 operation is one RN64 of its exact operands."""
    L = ['(* Generated by orl/emit.py coq; do not edit. The P32 operation graphs in the FLT model of binary64 (no overflow,',
         '   no sign of zero): the same definitions emit.py renders as Orlog laws and as the native C sweep program. *)',
         'From Coq Require Import Reals.', 'From Flocq Require Import Core.', 'Open Scope R_scope.', '',
         'Notation fexp64 := (FLT_exp (-1074) 53).', 'Notation format64 := (generic_format radix2 fexp64).',
         'Notation RN64 := (round radix2 fexp64 ZnearestE).', '',
         '(* kk = 2^29 + 1; mm = 1.5 * 2^-97; tt = 2^-126; hh = 2^-150 *)',
         'Definition KK : R := 536870913.', 'Definition MM : R := 3 * bpow radix2 (-98).',
         'Definition TT : R := bpow radix2 (-126).', 'Definition HH : R := bpow radix2 (-150).', '',
         '(* narrow: if |v| <= hh then v * 0.0; otherwise if |v| < tt then (v + mm) - mm; otherwise (kk*v) - ((kk*v) - v) *)',
         'Definition narrow (v : R) : R :=', '  if Rle_dec (Rabs v) HH then RN64 (v * 0)',
         '  else if Rlt_dec (Rabs v) TT then RN64 (RN64 (v + MM) - MM)',
         '  else RN64 (RN64 (KK * v) - RN64 (RN64 (KK * v) - v)).', '']
