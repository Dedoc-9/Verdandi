(* The EXP32 statement, frozen before its proof and before any run of the implementation (2026-11-14). Graph.v is
   generated by orl/emit2.py from the same stages it renders as an Orlog law and as the native sweep program. Model:
   Flocq's FLT formats, binary64 as FLT(-1074, 53) and binary32 as FLT(-149, 24), both without an upper exponent bound,
   so no overflow, and the sign of a zero is not seen. Author: the assistant.

   EXP32: for every binary32 x at most XMAX, the graph returns a faithful binary32 rounding of exp x (one of the two
   binary32 values that bracket it). XMAX = 11629079 / 2^17 = 88.72283172607421875 (bits 42B17217) is the largest
   binary32 x whose exp is below binary32's largest number; that it is so is not part of this statement (the model has
   no overflow) and is left to the exhaustive sweep. There is no lower limit: below -160 the graph clamps, and the
   result is zero. *)
From Coq Require Import Reals.
From Flocq Require Import Core.
From MKF.f32 Require Import F32_Statement.
From MKF.exp32 Require Import Graph.
Open Scope R_scope.

Definition XMAX : R := 11629079 / 131072.

Definition EXP32 : Prop :=
  forall x : R, format32 x -> x <= XMAX -> faithful32 (exp x) (g_exp32 x).
