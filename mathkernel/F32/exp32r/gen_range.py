# The constants of the EXP32 range proof (2026-11-14), exact rationals throughout (fractions.Fraction).
#   python3 -B exp32r/gen_range.py check    the margins, and an independent look with the decimal module
#   python3 -B exp32r/gen_range.py coq      prints Chain.v (the gate holds Chain.v to this output, byte for byte)
#   python3 -B exp32r/gen_range.py plants   writes the gate's plants into exp32r/plants/ from Chain.v's text and Range.v
#
# Upper chain: r = XMAX / 4096 = 11629079 / 2^29. exp r <= P7(r) + EPS (Taylor.exp_poly7), rounded up to U[0]; then
# exp(2t) = exp t * exp t, twelve times, U[i+1] = U[i]^2 rounded up; U[12] < FMAX32 = (2^24 - 1) 2^104.
# Lower chain: r2 = 11629080 / 2^29 (the binary32 number above XMAX, over 4096). exp r2 >= P7(r2) - EPS, rounded down
# to L[0]; L[i+1] = L[i]^2 rounded down; 2^128 < L[12].
# Every rounding is to a dyadic rational of BITS significant bits, so that each step is a small fact for lra.
# Every mode first asserts, exactly, each inequality the chain needs; it prints nothing of the machine.
import os, sys
from fractions import Fraction as F

BITS = 100
EPS = F(1, 3600000000000000)
RA = F(11629079, 2 ** 29)
RB = F(11629080, 2 ** 29)
FMAX = (2 ** 24 - 1) * 2 ** 104
P128 = 2 ** 128

def p7(r):
    return (5040 + r * (5040 + r * (2520 + r * (840 + r * (210 + r * (42 + r * (7 + r))))))) / 5040

def dyadic(q, up):
    """q > 0 rounded up (or down) to BITS significant bits."""
    assert q > 0
    k = BITS - 1 - ((q.numerator.bit_length() - q.denominator.bit_length()))
    while q * F(2) ** k >= 2 ** BITS: k -= 1
    while q * F(2) ** k < 2 ** (BITS - 1): k += 1
    s = q * F(2) ** k
    m = -((-s.numerator) // s.denominator) if up else s.numerator // s.denominator
    return F(m) / F(2) ** k

def chains():
    U = [dyadic(p7(RA) + EPS, True)]
    L = [dyadic(p7(RB) - EPS, False)]
    for _ in range(12):
        U.append(dyadic(U[-1] * U[-1], True))
        L.append(dyadic(L[-1] * L[-1], False))
    assert abs(RA) <= F(5, 128) and abs(RB) <= F(5, 128)
    assert p7(RA) + EPS <= U[0] and 0 <= L[0] <= p7(RB) - EPS
    for i in range(12):
        assert U[i] * U[i] <= U[i + 1] and 0 <= L[i + 1] <= L[i] * L[i]
    assert U[12] < FMAX and P128 < L[12]
    assert RA * 4096 == F(11629079, 131072) and RB * 4096 == F(11629080, 131072)
    return U, L

def lit(q):
    return str(q.numerator) if q.denominator == 1 else '%d / %d' % (q.numerator, q.denominator)

def arg(i, r):
    return lit(r) if i == 0 else '2 * (%s)' % arg(i - 1, r)

def chain_text(U, L):
    o = []
    a = o.append
    a('(* Generated by exp32r/gen_range.py coq; do not edit. The two chains of the EXP32 range proof, every constant an')
    a('   exact rational computed with fractions.Fraction and rounded to a dyadic rational of %d significant bits.' % BITS)
    a('   Upper: exp r <= P7(r) + 1/3600000000000000 for r = 11629079 / 2^29 (Taylor.exp_poly7), then twelve squarings,')
    a('   each bound u with u * u <= the next; the last is below (2^24 - 1) * 2^104, the largest binary32 number.')
    a('   Lower: exp r >= P7(r) - 1/3600000000000000 for r = 11629080 / 2^29, twelve squarings, each bound at most the')
    a('   square of the one before; the last is above 2^128. Standard library, Flocq.Raux (Rabs_le_inv) and Taylor.v only;')
    a('   nothing is admitted. *)')
    a('From Coq Require Import Reals Lra.')
    a('From Flocq Require Import Raux.')
    a('From MKF.exp32 Require Import Taylor.')
    a('Open Scope R_scope.')
    a('')
    a('Lemma sq_up (t u v : R) : exp t <= u -> u * u <= v -> exp (2 * t) <= v.')
    a('Proof.')
    a('  intros H1 H2. replace (2 * t) with (t + t) by ring. rewrite exp_plus. pose proof (exp_pos t) as P.')
    a('  apply Rle_trans with (2 := H2). apply Rmult_le_compat; lra.')
    a('Qed.')
    a('')
    a('Lemma sq_lo (t l v : R) : l <= exp t -> 0 <= l -> v <= l * l -> v <= exp (2 * t).')
    a('Proof.')
    a('  intros H1 H0 H2. replace (2 * t) with (t + t) by ring. rewrite exp_plus.')
    a('  apply Rle_trans with (1 := H2). apply Rmult_le_compat; lra.')
    a('Qed.')
    a('')
    for nm, r, B, up in (('up', RA, U, True), ('lo', RB, L, False)):
        e0 = 'exp (%s)' % arg(0, r)
        a('Lemma %s_0 : %s.' % (nm, ('%s <= %s' % (e0, lit(B[0]))) if up else ('%s <= %s' % (lit(B[0]), e0))))
        a('Proof.')
        a('  assert (A : Rabs (%s) <= 5 / 128) by (apply Rabs_le; lra).' % lit(r))
        a('  apply exp_poly7 in A. apply Rabs_le_inv in A. lra.')
        a('Qed.')
        a('')
        for i in range(1, 13):
            e = 'exp (%s)' % arg(i, r)
            a('Lemma %s_%d : %s.' % (nm, i, ('%s <= %s' % (e, lit(B[i]))) if up else ('%s <= %s' % (lit(B[i]), e))))
            a('Proof. apply (sq_%s _ _ _ %s_%d); lra. Qed.' % (nm, nm, i - 1))
            a('')
    a('Theorem chain_hi : exp (11629079 / 131072) < %d * %d.' % (2 ** 24 - 1, 2 ** 104))
    a('Proof.')
    a('  replace (11629079 / 131072) with (%s) by lra.' % arg(12, RA))
    a('  apply Rle_lt_trans with (1 := up_12). lra.')
    a('Qed.')
    a('')
    a('Theorem chain_lo : %d < exp (11629080 / 131072).' % P128)
    a('Proof.')
    a('  replace (11629080 / 131072) with (%s) by lra.' % arg(12, RB))
    a('  apply Rlt_le_trans with (2 := lo_12). lra.')
    a('Qed.')
    return '\n'.join(o) + '\n'

def sub(t, a, b):
    assert t.count(a) == 1, (a, t.count(a))
    return t.replace(a, b)

def main():
    mode = sys.argv[1] if len(sys.argv) > 1 else 'check'
    U, L = chains()
    if mode == 'coq':
        sys.stdout.buffer.write(chain_text(U, L).encode('ascii'))
    elif mode == 'check':
        from decimal import Decimal, getcontext
        getcontext().prec = 80
        hi = (Decimal(11629079) / Decimal(131072)).exp()
        lo = (Decimal(11629080) / Decimal(131072)).exp()
        print('upper chain: U[12] < FMAX32, relative margin (FMAX32 - U[12]) / FMAX32 = %.6e' % float(F(FMAX - U[12], FMAX)))
        print('lower chain: 2^128 < L[12], relative margin (L[12] - 2^128) / 2^128     = %.6e' % float(F(L[12] - P128, P128)))
        print('rounding of the first bounds: U[0] - (P7(r) + EPS) = %.3e, (P7(r2) - EPS) - L[0] = %.3e'
              % (float(U[0] - p7(RA) - EPS), float(p7(RB) - EPS - L[0])))
        print('decimal (80 digits, not part of the proof): exp(XMAX)            = %s' % hi)
        print('decimal:                                    FMAX32               = %d' % FMAX)
        print('decimal: 1 - exp(XMAX) / FMAX32                                  = %.6e' % float(1 - hi / Decimal(FMAX)))
        print('decimal:                                    exp(11629080/131072) = %s' % lo)
        print('decimal:                                    2^128                = %d' % P128)
        print('decimal: exp(11629080/131072) / 2^128 - 1                        = %.6e' % float(lo / Decimal(P128) - 1))
        print('decimal: U[12] / exp(XMAX) - 1 = %.3e ; 1 - L[12] / exp(11629080/131072) = %.3e'
              % (float(Decimal(U[12].numerator) / Decimal(U[12].denominator) / hi - 1),
                 float(1 - Decimal(L[12].numerator) / Decimal(L[12].denominator) / lo)))
        ok = Decimal(lit_dec(U[12])) > hi and hi < FMAX and Decimal(lit_dec(L[12])) < lo and lo > P128
        print('RANGE CONSTANTS %s: both margins exist (%d-bit chains, 12 squarings each)' % ('CHECKED' if ok else 'FAILED', BITS))
        sys.exit(0 if ok else 1)
    elif mode == 'plants':
        here = os.path.dirname(os.path.abspath(__file__)); pd = os.path.join(here, 'plants'); os.makedirs(pd, exist_ok=True)
        def wr(n, t): open(os.path.join(pd, n), 'w', encoding='ascii', newline=chr(10)).write(t)
        c = chain_text(U, L); rg = open(os.path.join(here, 'Range.v'), encoding='ascii').read()
        # a wrong constant in the upper chain: the bound after the sixth squaring a little too small for its step
        U2 = list(U); U2[6] = dyadic(U[6] * (1 - F(1, 2 ** 20)), True)
        assert U2[5] * U2[5] > U2[6]
        wr('Chain_upper.v', chain_text(U2, L))
        # a wrong constant in the lower chain: the bound after the ninth squaring a little too large for its step
        L2 = list(L); L2[9] = dyadic(L[9] * (1 + F(1, 2 ** 20)), False)
        assert L2[9] > L2[8] * L2[8]
        wr('Chain_lower.v', chain_text(U, L2))
        # a chain that is not the generator's output, though it means the same
        wr('Chain_edited.v', sub(c, 'Proof. apply (sq_up _ _ _ up_3); lra. Qed.', 'Proof. apply (sq_up _ _ _ up_3); lra.  Qed.'))
        # an admitted lemma in the proof file
        cut = rg.index('Proof.', rg.index('Lemma fmax_format')); end = rg.index('Qed.', cut) + len('Qed.')
        assert rg.count('Lemma fmax_format') == 1
        wr('Range_admitted.v', rg[:cut] + 'Admitted.' + rg[end:])
        # a proof file that defines statements of its own
        wr('Range_shadow.v', '\n'.join(['From Coq Require Import Reals.', 'Definition EXP32_RANGE : Prop := True.',
                                        'Definition EXP32_SHARP : Prop := True.', 'Theorem exp32_range : EXP32_RANGE.',
                                        'Proof. exact I. Qed.', 'Theorem exp32_sharp : EXP32_SHARP.', 'Proof. exact I. Qed.', '']))
        print('plants written: ' + ', '.join(sorted(os.listdir(pd))))
    else:
        sys.exit('usage: gen_range.py check | coq | plants')

def lit_dec(q):
    from decimal import Decimal
    return Decimal(q.numerator) / Decimal(q.denominator)

if __name__ == '__main__':
    main()
